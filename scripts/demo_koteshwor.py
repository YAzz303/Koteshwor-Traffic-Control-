"""Demo for a screen recording: Koteshwor at high demand, best DQN first, then fixed-time.

Usage (from the project folder):
    uv run python scripts/demo_koteshwor.py                     # 45 simulated minutes each
    uv run python scripts/demo_koteshwor.py --minutes 90 --delay 0
    uv run python scripts/demo_koteshwor.py --headless          # no GUI, just check it runs

Opens one full-screen SUMO-GUI window per controller, zoomed on the junction, starts it and
closes it at the end. The window title shows which controller runs (live_dqn.sumocfg, then
live_fixed.sumocfg). Both runs use the high demand preset with the fixed test seed, so the traffic
is identical. Between the two runs the script waits for Enter, so you can set up the recorder.

Results go to live/demo-koteshwor-high/ (git-ignored), with a comparison of the two runs. With
fewer than 90 minutes the numbers cover only that part of the episode, so they differ from the
results in docs/final/.
"""

import argparse
from pathlib import Path

import yaml

from tlcs.compare import compare_session
from tlcs.live import live_session
from tlcs.settings import load_yaml

ROOT = Path(__file__).resolve().parents[1]
PRESET = ROOT / "settings" / "koteshwor_testing_high.yaml"
BEST_MODEL = ROOT / "model" / "koteshwor-dqn-1000" / "checkpoints" / "episode_1000"
OUT = ROOT / "live" / "demo-koteshwor-high"
CONTROLLERS = (("dqn", "best DQN (1000 episodes)"), ("fixed", "fixed-time baseline"))


def main() -> None:
    """Parse arguments and run the two controllers one after the other."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--minutes", type=int, default=45, help="Simulated minutes per run (max 90; default 45)"
    )
    parser.add_argument(
        "--delay", type=float, default=20, help="GUI delay per simulated second in ms (default 20)"
    )
    parser.add_argument(
        "--view-radius", type=float, default=150, help="Meters shown around the junction"
    )
    parser.add_argument("--model-path", type=Path, default=BEST_MODEL)
    parser.add_argument("--no-pause", action="store_true", help="Don't wait for Enter between runs")
    parser.add_argument("--headless", action="store_true", help="Run without the GUI (for testing)")
    args = parser.parse_args()

    settings = load_yaml(PRESET)
    settings["gui"] = not args.headless
    settings["max_steps"] = min(args.minutes, 90) * 60
    OUT.mkdir(parents=True, exist_ok=True)
    demo_settings = OUT / "demo_settings.yaml"
    demo_settings.write_text(
        "# Generated by scripts/demo_koteshwor.py from settings/koteshwor_testing_high.yaml\n"
        + yaml.safe_dump(settings, sort_keys=False),
        encoding="utf-8",
    )

    print(
        f"Koteshwor, high demand ({settings['n_cars_generated']} cars per 90 min), seed "
        f"{settings['episode_seed']}, {settings['max_steps'] // 60} simulated minutes per run."
    )
    for i, (name, title) in enumerate(CONTROLLERS):
        if i > 0 and not args.no_pause and not args.headless:
            input(f"\nNext: {title}. Press Enter to start ...")
        print(f"\nRunning {title} ...")
        live_session(
            settings_file=demo_settings,
            controllers=[name],
            model_path=args.model_path,
            out_path=OUT / name,
            delay=args.delay,
            view_radius=args.view_radius,
        )

    print("\nComparison of the two runs:")
    compare_session(
        [OUT / name / name for name, _ in CONTROLLERS],
        OUT / "comparison",
        labels=[title for _, title in CONTROLLERS],
    )


if __name__ == "__main__":
    main()
